# ---------- 生成 ----------
L = []
L.append('## 5 代表性公办初中个案')
L.append('')
L.append('> **选人标准预注册**（分析前固定，见 `design.md` 3.4）：头部 = 主口径前 5；')
L.append('> 明显上升 = SEN ≥ 1.0 且 Δrel 最大 3；明显下降 = SEN ≤ −1.0 且 SEN 最负 3。')
L.append('> 每所含逐年事实、**推断（标注证据强度）**与**至少一条反向证据**。')
L.append('> 分类与显著性口径见 4.4（**Bonferroni 校正后 0 所显著**）。')
L.append('')

for gi, (gname, names) in enumerate(GROUPS, 1):
    L.append(f'### 5.{gi} {gname}')
    L.append('')
    for n in names:
        w, t = W[n], T[n]
        rk = int(w['rank_P_wq_comb'])
        q5 = st.fmean([float(w[f'quota4_{y}']) for y in YEARS])
        L.append(f"**{sh(n)}**｜主口径第 {rk} 名｜`{t['trend_class']}`")
        L.append('')
        L.append('| 年 | 区属 4 线名额 | 名额加权均分 | rel（相对当年公办池中位） | 当年位次 |')
        L.append('|---|---|---|---|---|')
        for y in YEARS:
            q = w.get(f'quota4_{y}', '') or '—'
            L.append(f"| {y} | {q} | {float(w[f'mean_score_base4_wq_{y}']):.1f} "
                     f"| {float(w[f'rel_{y}']):+.1f} | {float(w[f'rank_base4_wq_{y}']):.0f} |")
        L.append('')
        L.append(f"- **事实**：P综合 = {float(w['P_wq_comb']):.4f}"
                 f"（全身 {w['rank_P_wq_all']} / 头部 {w['rank_P_wq_head']} / 尾部 {w['rank_P_wq_tail']}）；"
                 f"等权口径第 {w['rank_P_eq_comb']} 名"
                 f"（位次差 {int(w['rank_P_eq_comb']) - rk:+d}）；"
                 f"区属 4 线名额五年均 {q5:.1f} 个。")
        L.append(f"- **事实（趋势）**：Sen = {t['sen']}、近 3 年 Sen = {t['sen_recent3']}、"
                 f"Δrel = {t['delta_rel']}（{t['rel_first']} → {t['rel_last']}）；"
                 f"Mann-Kendall p = {t['mk_p']}（Bonferroni 校正后 {t['mk_p_bonferroni']}）。")
        L.append('')
        L.append(NOTE[n])
        L.append('')
        L.append(f'**反向证据**：{REVERSE[n]}')
        L.append('')
        L.append('---')
        L.append('')

NEW = '\n'.join(L)

# ---------- 断言（全部通过才落盘）----------
assert len(HEAD5) == TOP_N and len(UP3) == K_N and len(DN3) == K_N
for n in HEAD5 + UP3 + DN3:
    assert n in NOTE, f'{sh(n)} 缺「推断」文案——入选名单变了，请补充'
    assert n in REVERSE, f'{sh(n)} 缺「反向证据」文案——入选名单变了，请补充'
    assert W[n]['row_type'] == 'ranked', f'{sh(n)} 非 ranked'
    assert int(W[n]['years_included']) == 5, f'{sh(n)} 非五年全勤'
for n in UP3:
    assert T[n]['trend_class'] == '明显上升', f'{sh(n)} 应为明显上升'
for n in DN3:
    assert T[n]['trend_class'] == '明显下降', f'{sh(n)} 应为明显下降'
assert NEW.count('| 2022 |') == 11, f'逐年表数量异常：{NEW.count("| 2022 |")}'
assert NEW.count('- **事实**：') == 11, '事实段数量异常'
assert NEW.count('- **事实（趋势）**：') == 11, '趋势事实段数量异常'
assert NEW.count('**推断（证据强度：') == 11, '推断段数量异常'
assert NEW.count('**反向证据**：') == 11, '反向证据段数量异常'
assert NEW.count('---') >= 11, '分隔符不足'
assert 'None' not in NEW and 'nan' not in NEW, '含 None/nan'

# ---------- 替换第 5 章 ----------
s = REPORT.read_text(encoding='utf-8')
m5 = re.search(r'^## 5 .*$', s, re.M)
assert m5, '未找到第 5 章标题'
m6 = re.search(r'^## 附录 A .*$', s, re.M)
assert m6, '未找到附录 A 标题'
assert m5.start() < m6.start(), '第 5 章应在附录 A 之前'
# 旧第 5 章可能含 5.6/5.7 等小节 —— 一并替换。
# ⚠️ 若 5.4 梅陇专题已存在（由 build_ch5_topic_pt.py 插入），**必须先摘出、替换后再插回**，
# 否则整块替换会把它抹掉，导致两个脚本都无法幂等重跑。
_m54 = re.search(r'^### 5\.4 .*$', s, re.M)
_keep54 = ''
if _m54 and _m54.start() < m6.start():
    # 5.4 块内有多个 '---'，不能按第一个分隔符截断；改为**摘到附录 A 之前**。
    _end = m6.start()
    _keep54 = s[_m54.start():_end].rstrip('\n') + '\n'
    s = s[:_m54.start()] + s[_end:]
    m5 = re.search(r'^## 5 .*$', s, re.M)
    m6 = re.search(r'^## 附录 A .*$', s, re.M)
    assert m5 and m6, '摘除 5.4 后未重新定位第 5 章 / 附录 A'
new_ch5 = NEW.rstrip('\n') + '\n\n' + _keep54
out = s[:m5.start()] + new_ch5 + '\n' + s[m6.start():]
assert len(out) > 0
if _keep54:
    assert '5.4 用户指定专题' in out, '5.4 专题在替换中丢失'
    # 直接检查 5.4 块被**逐字**保留（比数分隔符更可靠）
    assert _keep54.strip() and _keep54.strip() in out, '5.4 块未逐字保留到报告中'
else:
    assert len(out) >= len(s) - len(NEW) + len(NEW), '拼装异常'
REPORT.write_text(out, encoding='utf-8')

print(f'第 5 章已重写（{len(HEAD5) + len(UP3) + len(DN3)} 所 = 头部 5 + 上升 3 + 下降 3）')
for gname, names in GROUPS:
    print(f'  {gname}: ' + '、'.join(sh(x) for x in names))
_msg = '已保留' if _keep54 else '本次一并生成（首次）'
print('  5.4 梅陇专题：' + _msg)
print(f'  报告 {len(s)} → {len(out)} 字符')
print('  每所均含：逐年表 5 行 + 事实 2 条 + 推断 1 段 + 反向证据 1 段')
