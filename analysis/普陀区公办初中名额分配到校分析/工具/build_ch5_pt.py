UP3 = [r['junior_high_school'] for r in
       sorted((r for r in T.values() if r['trend_class'] == '明显上升'),
              key=lambda r: -float(r['delta_rel']))[:K_N]]
DN3 = [r['junior_high_school'] for r in
       sorted((r for r in T.values() if r['trend_class'] == '明显下降'),
              key=lambda r: float(r['sen']))[:K_N]]
GROUPS = [('主口径前 5 名', HEAD5), ('明显上升 3 名（Δrel 最大）', UP3),
          ('明显下降 3 名（SEN 最负）', DN3)]

