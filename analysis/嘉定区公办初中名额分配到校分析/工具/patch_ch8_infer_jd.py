# -*- coding: utf-8 -*-
"""补齐第 8 章剩余 4 所个案的「推断（证据强度）」标注，使 11 所全部满足事实/推断分离。"""
import os

D = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
p = f'{D}/分析报告.md'
s = open(p, encoding='utf-8').read()

# (定位锚子, 要插入的推断段)
PATCH = [
    ('**反向证据**：2026 年它的名额 14.6 个属全区中位附近',
     '**推断（证据强度：弱）**：它 2026 年位次跌到第 24 位而名额并不少，'
     '**可能与强校涌入同时发生**——但仓库内无生源数据，'
     '无法判断是「自身退步」还是「别人进步」，仅记录现象供后续核查。'),
    ('**反向证据**：2026 年它回到第 8 位、加权均分 745.2',
     '**推断（证据强度：中）**：2023 年的骤降与当年新增第 3 条区属线无关'
     '（第 3 条线 2025 年才出现），**更可能与该校当年生源波动有关**，'
     '但同样无数据可验证。'),
    ('**反向证据**：2026 年加权均分 734.0 看似不低',
     '**推断（证据强度：弱）**：它 2022–2024 连续三年位次从第 25 升到第 22，'
     '但 2025 年起回落，**这个转折与上师嘉新 2025 年扩容在时间上接近**，'
     '是否相关无法判定——两条线名额此消彼长，但**没有学校级名额分配的因果证据**。'),
    ('**反向证据**：名额 5.4 个同样偏少',
     '**推断（证据强度：弱）**：2025 年加权均分跌到 694.9（全表最低区间）'
     '且位次跌到第 38，**两项指标同时恶化**，'
     '倾向于存在真实变化而非名额结构问题；但**本数据无法排除考生构成变化**。'),
]

n = 0
for anchor, ins in PATCH:
    if anchor not in s:
        print(f'⚠ 未找到锚子：{anchor[:30]}')
        continue
    s = s.replace(anchor, ins + anchor, 1)
    n += 1
open(p, 'w', encoding='utf-8').write(s)
print(f'已补 {n} 处推断标注')
